import { execFileSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "../..");
const bootstrapSource = join(scriptDir, "appimage-bootstrap.c");
const executableMode = 0o755;

function fail(message) {
  throw new Error(`patch-appimage-bootstrap: ${message}`);
}

function requireFile(path, description) {
  const stat = lstatSync(path, { throwIfNoEntry: false });
  if (!stat?.isFile()) {
    fail(`${description} is missing: ${path}`);
  }
}

function requireExecutable(path, description) {
  requireFile(path, description);
  if ((lstatSync(path).mode & executableMode) === 0) {
    fail(`${description} is not executable: ${path}`);
  }
}

function validateGeneratedAppRun(appDir, path) {
  requireExecutable(path, "generated AppRun shell");
  const generatedShell = readFileSync(path, "utf8");
  if (!generatedShell.includes("# autogenerated by linuxdeploy")) {
    fail(`AppRun is not the linuxdeploy-generated shell: ${path}`);
  }
  if (!generatedShell.includes("AppRun.wrapped")) {
    fail(`linuxdeploy AppRun shell does not delegate to AppRun.wrapped: ${path}`);
  }
  requireExecutable(join(appDir, "AppRun.wrapped"), "wrapped native AppRun");
}

function findAppImagePlugin() {
  const cacheRoot = process.env.XDG_CACHE_HOME || join(homedir(), ".cache");
  const candidates = [
    process.env.APPIMAGE_PLUGIN,
    join(cacheRoot, "tauri", "linuxdeploy-plugin-appimage.AppImage"),
  ].filter(Boolean);
  const plugin = candidates.find((candidate) => {
    const stat = lstatSync(candidate, { throwIfNoEntry: false });
    return stat?.isFile() && (stat.mode & 0o111) !== 0;
  });
  if (!plugin) {
    fail(
      "linuxdeploy-plugin-appimage.AppImage is missing; set APPIMAGE_PLUGIN or run the Tauri AppImage build first",
    );
  }
  return plugin;
}

function compileBootstrap(output) {
  requireFile(bootstrapSource, "bootstrap source");
  const compiler = process.env.CC || "cc";
  execFileSync(
    compiler,
    ["-std=c11", "-O2", "-static", "-s", bootstrapSource, "-o", output],
    { cwd: repoRoot, stdio: "inherit" },
  );
  chmodSync(output, executableMode);
}

export function installAppRunBootstrap(appDir) {
  if (!existsSync(appDir)) {
    fail(`AppDir is missing: ${appDir}`);
  }
  const appRun = join(appDir, "AppRun");
  const appRunShell = join(appDir, "AppRun.shell");
  requireFile(appRun, "generated AppRun");
  const generatedShellPath = existsSync(appRunShell) ? appRunShell : appRun;
  validateGeneratedAppRun(appDir, generatedShellPath);
  if (existsSync(appRunShell)) {
    const existing = readFileSync(appRun);
    if (existing.subarray(0, 4).equals(Buffer.from([0x7f, 0x45, 0x4c, 0x46]))) {
      return;
    }
    fail(`AppRun.shell already exists but AppRun is not a bootstrap ELF: ${appDir}`);
  }

  const stagingDir = mkdtempSync(join(appDir, ".hooviestar-appimage-bootstrap-"));
  const temporaryBootstrap = join(stagingDir, "AppRun");
  try {
    compileBootstrap(temporaryBootstrap);
    renameSync(appRun, appRunShell);
    try {
      renameSync(temporaryBootstrap, appRun);
    } catch (error) {
      renameSync(appRunShell, appRun);
      throw error;
    }
    chmodSync(appRunShell, executableMode);
    console.log(`Installed static AppRun bootstrap in ${appDir}`);
  } finally {
    rmSync(stagingDir, { recursive: true, force: true });
  }
}

export function repackAppImage(appDir, appImage) {
  const appImagePlugin = findAppImagePlugin();
  const temporaryOutput = `${appImage}.bootstrap.tmp`;
  rmSync(temporaryOutput, { force: true });
  const environment = {
    ...process.env,
    APPIMAGE_EXTRACT_AND_RUN: "1",
    LDAI_OUTPUT: temporaryOutput,
    OUTPUT: temporaryOutput,
  };
  try {
    execFileSync(
      appImagePlugin,
      ["--appimage-extract-and-run", "--appdir", appDir],
      { cwd: repoRoot, env: environment, stdio: "inherit" },
    );
    requireFile(temporaryOutput, "repacked AppImage");
    if (existsSync(`${appImage}.sig`)) {
      fail(`refusing to replace a signed AppImage without re-signing: ${appImage}`);
    }
    renameSync(temporaryOutput, appImage);
  } finally {
    rmSync(temporaryOutput, { force: true });
  }
}

export function patchAndRepackAppImage(appDir, appImage) {
  requireFile(appImage, "AppImage");
  if (existsSync(`${appImage}.sig`)) {
    fail(`refusing to replace a signed AppImage without re-signing: ${appImage}`);
  }
  installAppRunBootstrap(appDir);
  repackAppImage(appDir, appImage);
}
function main() {
  const [appDir, appImage] = process.argv.slice(2);
  if (!appDir || !appImage) {
    fail("usage: node scripts/release/patch-appimage-bootstrap.mjs <AppDir> <AppImage>");
  }
  const resolvedAppImage = resolve(appImage);
  if (existsSync(`${resolvedAppImage}.sig`)) {
    fail(`refusing to leave a stale updater signature; use npm run tauri-appimage to re-sign ${resolvedAppImage}`);
  }
  patchAndRepackAppImage(resolve(appDir), resolvedAppImage);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
